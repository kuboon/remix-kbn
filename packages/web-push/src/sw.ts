/**
 * The service worker half: show what `./server` sends, and open its URL when it is clicked.
 *
 * Two ways to use it:
 *
 * - **Bundled** into a service worker of your own: call {@link installPushHandlers} with `self`.
 * - **Served as is**, with no bundler: {@link pushServiceWorkerScript} returns a complete classic
 *   service worker as a string, to answer `/sw.js` with.
 *
 * ```ts
 * router.get('/sw.js', () =>
 *   new Response(pushServiceWorkerScript({ defaultTitle: 'kagi' }), {
 *     headers: { 'content-type': 'text/javascript; charset=utf-8', 'service-worker-allowed': '/' },
 *   }))
 * ```
 *
 * It shows `title`, `body`, `icon`, `badge`, `tag` and `requireInteraction`, sets or clears the
 * app badge from `badgeCount` (Badging API, where supported), and on click focuses an open window
 * at `url` or opens one.
 *
 * @module
 */

export interface PushHandlerOptions {
  /** Used when a message has no title. */
  defaultTitle: string
}

/**
 * The parts of `ServiceWorkerGlobalScope` the handlers use, typed loosely so this module checks
 * without the `webworker` lib.
 */
// deno-lint-ignore no-explicit-any
export type ServiceWorkerScope = any

/**
 * Adds the `install`, `activate`, `push` and `notificationclick` handlers to a service worker.
 *
 * Self-contained on purpose — it refers to nothing outside its own body — so that
 * {@link pushServiceWorkerScript} can ship it as source text. That holds as long as whatever compiles
 * this module keeps `async`/`await` as they are (Deno, and bundlers targeting ES2017 or later, do); a
 * compile down to ES5 would replace them with helpers outside the function.
 */
export function installPushHandlers(scope: ServiceWorkerScope, options: PushHandlerOptions): void {
  // Take over at once: a new version of the worker should not wait for every tab to close.
  scope.addEventListener('install', (event: ServiceWorkerScope) => {
    event.waitUntil(scope.skipWaiting())
  })
  scope.addEventListener('activate', (event: ServiceWorkerScope) => {
    event.waitUntil(scope.clients.claim())
  })

  scope.addEventListener('push', (event: ServiceWorkerScope) => {
    let data: Record<string, unknown> = {}
    if (event.data) {
      try {
        const json = event.data.json()
        if (json && typeof json === 'object') data = json
      } catch {
        try {
          data = { body: event.data.text() }
        } catch {
          // Unreadable payload: show the default title alone.
        }
      }
    }
    const str = (v: unknown) => (typeof v === 'string' && v.trim() ? v : undefined)
    const url = str(data.url)
    const extra = data.data && typeof data.data === 'object' ? data.data : {}

    const show = scope.registration.showNotification(str(data.title) ?? options.defaultTitle, {
      body: str(data.body),
      icon: str(data.icon),
      badge: str(data.badge),
      tag: str(data.tag),
      requireInteraction: Boolean(data.requireInteraction),
      data: { ...extra, url },
    })

    // A missing or invalid count leaves the badge as it is; 0 clears it.
    const count = data.badgeCount
    const nav = scope.navigator
    let badge: Promise<unknown> = Promise.resolve()
    if (typeof count === 'number' && count >= 0 && nav && 'setAppBadge' in nav) {
      const n = Math.floor(count)
      badge = (n > 0 ? nav.setAppBadge(n) : nav.clearAppBadge()).catch(() => {})
    }

    event.waitUntil(Promise.all([show, badge]))
  })

  scope.addEventListener('notificationclick', (event: ServiceWorkerScope) => {
    event.notification.close()
    const url = event.notification.data?.url
    if (typeof url !== 'string' || !url) return
    event.waitUntil((async () => {
      const target = new URL(url, scope.location.href).href
      const windows = await scope.clients.matchAll({ type: 'window', includeUncontrolled: true })
      for (const client of windows) {
        if (client.url === target && 'focus' in client) return client.focus()
      }
      if (scope.clients.openWindow) return scope.clients.openWindow(target)
    })())
  })
}

/**
 * A complete classic service worker, as source text, that runs {@link installPushHandlers}. Serve
 * it from the scope it should control (`/sw.js` for the whole origin).
 */
export function pushServiceWorkerScript(options: PushHandlerOptions): string {
  return `// Generated by @remix-kbn/web-push.\n'use strict';\n(${installPushHandlers.toString()})(self, ${
    JSON.stringify(options)
  });\n`
}
